// 把服务端真实的运行时固定文字写进 client.js 的内联副本。
//
// 用法：node tools/gen-runtime-copy.mjs
// 改完 lib/ 里任何输出模板后跑一次；assert-runtime-copy.mjs 会拦住忘记跑的情况。
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { extractRuntimeCopy } from "./lib/extract-runtime-copy.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const copy = extractRuntimeCopy(root);

const START = "    // @generated by tools/gen-runtime-copy.mjs —— 以下文字全部抄自 lib/，改源码后请重跑。\n";
const OPEN = "    const RUNTIME_OUTPUT_COPY = ";

// 缩进成好读的多行字面量；内容是 JSON，所以键一律带引号。
function literal(value, indent) {
  const pad = " ".repeat(indent);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const items = value.map((v) => `${pad}  ${JSON.stringify(v)}`);
    return `[\n${items.join(",\n")},\n${pad}]`;
  }
  const entries = Object.entries(value).map(([k, v]) => {
    const rendered =
      v && typeof v === "object" ? literal(v, indent + 2) : JSON.stringify(v);
    return `${pad}  ${JSON.stringify(k)}: ${rendered}`;
  });
  return `{\n${entries.join(",\n")},\n${pad}}`;
}

const body = `${OPEN}${literal(copy, 4)};\n`;
const block = `${START}${body}`;

const clientPath = path.join(root, "lib", "client.js");
let client = fs.readFileSync(clientPath, "utf8");
if (client.includes("\r\n")) client = client.split("\r\n").join("\n");

const at = client.indexOf(START) >= 0 ? client.indexOf(START) : client.indexOf(OPEN);
if (at < 0) throw new Error("RUNTIME_OUTPUT_COPY anchor not found");

// 旧块的结束：从 at 开始找到这一行结尾的分号 + 换行。
let end = -1;
if (client.startsWith(START, at)) {
  const closeAt = client.indexOf("\n", at + START.length);
  end = client.indexOf("\n", client.indexOf("};", at)) + 1;
  void closeAt;
} else {
  end = client.indexOf("\n", at) + 1;
}

client = client.slice(0, at) + block + client.slice(end);
fs.writeFileSync(clientPath, client);
console.log(`client.js: RUNTIME_OUTPUT_COPY 已重写（shells=${copy.shells.length}, placeholders=${copy.placeholders.length}, notes=${copy.noteTemplates.length}）`);
